-- Нова воронка: … Замір → Проєктування → Очікує рішення клієнта → Проєкт погоджено →
-- Договір → Комплектування → Збирання → Монтаж → Закрито (+ Рекламація, Відмова).
-- «Змонтовано» → «Монтаж»: виконання монтажу видно з етапу плану (100 %). Журнал не переписуємо.
ALTER TABLE orders DROP CONSTRAINT orders_status_check;
-- На випадок, якщо етап плану не позначено: «Змонтовано» означало виконаний монтаж
UPDATE plan_tasks t SET progress = 100 FROM orders o WHERE o.id = t.order_id AND o.status = 'Змонтовано' AND t.stage = 'Монтаж' AND t.progress < 100;
UPDATE orders SET status = CASE status
    WHEN 'Закупівля матеріалів' THEN 'Комплектування'
    WHEN 'У виробництві' THEN 'Збирання'
    WHEN 'Готово до відвантаження' THEN 'Збирання'
    ELSE 'Монтаж' END
 WHERE status IN ('Закупівля матеріалів', 'У виробництві', 'Готово до відвантаження', 'Доставка / монтаж призначено', 'Змонтовано');
ALTER TABLE orders ADD CONSTRAINT orders_status_check CHECK (status IN ('Звернення','Прорахунок','Замір','Проєктування','Очікує рішення клієнта',
  'Проєкт погоджено','Договір / аванс отримано','Комплектування','Збирання','Монтаж','Закрито','Відмова','Рекламація'));

-- Норми днів: старі назви → нові
UPDATE settings
   SET value = jsonb_set(value, '{norms}',
         ((value->'norms') - 'Закупівля матеріалів' - 'У виробництві' - 'Готово до відвантаження' - 'Доставка / монтаж призначено' - 'Змонтовано')
         || jsonb_strip_nulls(jsonb_build_object(
              'Комплектування', value->'norms'->'Закупівля матеріалів',
              'Збирання', value->'norms'->'У виробництві',
              'Монтаж', value->'norms'->'Доставка / монтаж призначено')))
 WHERE key = 'main' AND jsonb_typeof(value->'norms') = 'object';
